/** The brand colour, or white for near-black marks (their monochrome form) so they read on black. */
export function onBlack(hex: string): string {
  const n = Number.parseInt(hex, 16);
  const lum = (0.2126 * ((n >> 16) & 255) + 0.7152 * ((n >> 8) & 255) + 0.0722 * (n & 255)) / 255;
  return lum < 0.22 ? '#ffffff' : `#${hex}`;
}

export function buildWall(): string {
  return `<div class="fin__wall" aria-hidden="true">${AUTOPILOT.map(
    ([icon]) =>
      `<i class="fin__tool" style="--c:${onBlack(icon.hex)}"><svg viewBox="0 0 24 24"><path d="${icon.path}"/></svg></i>`,
  ).join('')}</div>`;
}
